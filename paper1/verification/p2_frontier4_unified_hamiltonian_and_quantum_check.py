def compute_schwarzschild_rw_zerilli_modes(r_H: float = 2.0, j: int = 2, n_modes: int = 2):
    """
    Extract exact lowest graviton mode frequencies omega_{RW}(j, n), omega_{Z}(j, n), and
    minimal-scalar (no Weyl tidal -6M/r^3) omega_{sc}(j, n) on a Schwarzschild exterior
    cavity r_* in [-25, +25] directly from the second-variation operators of Module B!
    """
    M = 0.5 * r_H
    n_grid = 500
    rs = np.linspace(-25.0, 25.0, n_grid)
    dr = rs[1] - rs[0]
    r = np.where(rs > 4.0 * M, rs, r_H + r_H * np.exp((rs - r_H) / (2.0 * M)))
    r = np.maximum(r, r_H + 1e-12)
    for _ in range(30):
        u = np.maximum(r / r_H - 1.0, 1e-15)
        fv = r + r_H * np.log(u) - rs
        dfv = 1.0 + 1.0 / u
        r = np.maximum(r - fv / dfv, r_H + 1e-14)
    f = 1.0 - r_H / r
    lam = 0.5 * (j - 1) * (j + 2)
    V_RW = f * (j * (j + 1) / (r**2) - 6.0 * M / (r**3))
    V_Z = f * (
        2 * lam**2 * (lam + 1) * r**3 + 6 * lam**2 * M * r**2 + 18 * lam * M**2 * r + 18 * M**3
    ) / ((r**3) * ((lam * r + 3.0 * M) ** 2))
    V_sc = f * (j * (j + 1) / (r**2) + 2.0 * M / (r**3))

    kin_d = np.full(n_grid, 2.0 / (dr**2))
    kin_o = np.full(n_grid - 1, -1.0 / (dr**2))
    om_RW = np.sqrt(np.maximum(eigh_tridiagonal(kin_d + V_RW, kin_o, eigvals_only=True)[:n_modes], 0.0))
    om_Z = np.sqrt(np.maximum(eigh_tridiagonal(kin_d + V_Z, kin_o, eigvals_only=True)[:n_modes], 0.0))
    om_sc = np.sqrt(np.maximum(eigh_tridiagonal(kin_d + V_sc, kin_o, eigvals_only=True)[:n_modes], 0.0))
    return om_RW, om_Z, om_sc


def build_su2_corner(M: int):
    states = []
    two_J = M
    while two_J >= 0:
        k = (M - two_J) // 2
        mult = math.comb(M, k) - (math.comb(M, k - 1) if k >= 1 else 0)
        J = 0.5 * two_J
        for cidx in range(mult):
            for two_m in range(-two_J, two_J + 1, 2):
                states.append((J, 0.5 * two_m, cidx))
        two_J -= 2
    dim_c = len(states)
    st_map = {st: i for i, st in enumerate(states)}
    Jz = np.zeros((dim_c, dim_c), dtype=complex)
    Jp = np.zeros((dim_c, dim_c), dtype=complex)
    for i, (J, m, cidx) in enumerate(states):
        Jz[i, i] = m
        if m + 1.0 <= J + 1e-9:
            Jp[st_map[(J, m + 1.0, cidx)], i] = math.sqrt(J * (J + 1.0) - m * (m + 1.0))
    Jm = Jp.conj().T
    return dict(dim=dim_c, states=states, Jx=0.5 * (Jp + Jm), Jy=-0.5j * (Jp - Jm), Jz=Jz)


